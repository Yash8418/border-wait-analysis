"""Build clean datasets from the raw CBSA files.

Outputs (in data/processed/):
- windsor_hourly.csv.gz   one row per crossing per hour (2010-2019)
- windsor_monthly.csv     % of time the service standard was met, per month (2019-2025)
- quality_report.md       what was cleaned, dropped and why

Usage:
    python -m border_wait.clean
"""

from __future__ import annotations

import glob
from pathlib import Path

import pandas as pd

from border_wait.parsing import fiscal_to_calendar_month, normalize_crossing, parse_timestamp, parse_wait

ROOT = Path(__file__).resolve().parents[2]
RAW_DIR = ROOT / "data" / "raw"
OUT_DIR = ROOT / "data" / "processed"
LOCAL_TZ = "America/Toronto"


def read_quarterly_files(raw_dir: Path = RAW_DIR) -> pd.DataFrame:
    """Read every quarterly file, unifying the column names that changed over the years."""
    frames = []
    for path in sorted(glob.glob(str(raw_dir / "border-wait-times-*.csv"))):
        frame = pd.read_csv(path, dtype=str, keep_default_na=False)
        frame.columns = ["office", "location", "updated", "commercial", "travellers"]
        frame["source_file"] = Path(path).name
        frames.append(frame)
    if not frames:
        raise FileNotFoundError(f"No quarterly files found in {raw_dir}. Run scripts/fetch_data.py first.")
    return pd.concat(frames, ignore_index=True)


def clean_hourly(raw: pd.DataFrame) -> tuple[pd.DataFrame, dict]:
    """Clean raw readings into one row per crossing per hour, plus stats for the quality report."""
    stats: dict = {"raw_rows": len(raw)}
    df = raw.copy()

    df["crossing"] = df["office"].map(normalize_crossing)
    stats["dropped_other_crossings"] = int(df["crossing"].isna().sum())
    df = df.dropna(subset=["crossing"])

    df["timestamp"] = pd.to_datetime(df["updated"].map(parse_timestamp), utc=True).dt.tz_convert(LOCAL_TZ)

    for flow in ("travellers", "commercial"):
        parsed = df[flow].map(parse_wait)
        df[f"{flow}_status"] = parsed.str[0]
        df[f"{flow}_wait_min"] = parsed.str[1].astype(float)

    # Readings are taken roughly hourly (e.g. 13:52, 14:54). Bucket them into the hour they describe
    # and keep the latest reading per crossing per hour.
    df["hour"] = df["timestamp"].dt.floor("h", ambiguous="NaT", nonexistent="shift_forward")
    df = df.dropna(subset=["hour"]).sort_values("timestamp")
    before = len(df)
    df = df.drop_duplicates(subset=["crossing", "hour"], keep="last")
    stats["duplicates_removed"] = before - len(df)

    clean = df[
        ["crossing", "hour", "travellers_wait_min", "travellers_status",
         "commercial_wait_min", "commercial_status", "source_file"]
    ].rename(columns={"hour": "timestamp"}).reset_index(drop=True)

    stats["clean_rows"] = len(clean)
    stats["traveller_status_counts"] = clean["travellers_status"].value_counts().to_dict()
    stats["date_range"] = (clean["timestamp"].min(), clean["timestamp"].max())
    stats["rows_per_crossing"] = clean["crossing"].value_counts().to_dict()
    stats["gaps_over_6h"] = count_gaps(clean, hours=6)
    return clean, stats


def count_gaps(df: pd.DataFrame, hours: int) -> dict[str, int]:
    """Count stretches with no readings longer than `hours`, per crossing."""
    gaps = {}
    for crossing, group in df.groupby("crossing"):
        gap_seconds = group["timestamp"].sort_values().diff().dt.total_seconds()
        gaps[crossing] = int((gap_seconds > hours * 3600).sum())
    return gaps


def clean_monthly(raw_dir: Path = RAW_DIR) -> pd.DataFrame:
    """Clean the monthly service-standard file (Apr 2019 onwards)."""
    path = raw_dir / "historical-border-wait-times-2019-04-01-to-2025-10-31.csv"
    raw = pd.read_csv(path, dtype=str, keep_default_na=False)
    raw.columns = ["office", "month", "fiscal_year", "pct_met"]

    year_month = [fiscal_to_calendar_month(m, fy) for m, fy in zip(raw["month"], raw["fiscal_year"])]
    monthly = pd.DataFrame(
        {
            "crossing": raw["office"].map(normalize_crossing),
            "month": pd.to_datetime([f"{y}-{m:02d}-01" for y, m in year_month]),
            "pct_met_service_standard": raw["pct_met"].str.rstrip("%").astype(float),
        }
    )
    return monthly.dropna(subset=["crossing"]).sort_values(["crossing", "month"]).reset_index(drop=True)


def quality_report(stats: dict, monthly: pd.DataFrame) -> str:
    start, end = stats["date_range"]
    status_lines = "\n".join(
        f"| {status} | {count:,} |" for status, count in sorted(stats["traveller_status_counts"].items())
    )
    crossing_lines = "\n".join(
        f"| {crossing} | {rows:,} | {stats['gaps_over_6h'].get(crossing, 0)} |"
        for crossing, rows in sorted(stats["rows_per_crossing"].items())
    )
    return f"""# Data quality report

Generated by `python -m border_wait.clean`.

## Hourly readings (2010–2019)

- Raw rows read: **{stats['raw_rows']:,}**
- Rows from other crossings dropped: {stats['dropped_other_crossings']:,}
- Duplicate readings in the same hour removed: {stats['duplicates_removed']:,}
- Clean hourly rows: **{stats['clean_rows']:,}**
- Date range: {start:%Y-%m-%d %H:%M} to {end:%Y-%m-%d %H:%M} ({LOCAL_TZ})

### Traveller wait values

| Status | Rows |
|---|---|
{status_lines}

`reported` includes "No delay" (stored as 0 minutes). `missed` means CBSA didn't record a value that hour; `closed` covers "Closed" and "Temporarily closed". Non-reported hours are kept with an empty wait so they aren't mistaken for zero.

### Coverage by crossing

| Crossing | Hourly rows | Gaps longer than 6 hours |
|---|---|---|
{crossing_lines}

## Monthly service standard (Apr 2019 – {monthly['month'].max():%b %Y})

- Rows: {len(monthly)} ({monthly['crossing'].nunique()} crossings)
- Source reports the percentage of the month in which CBSA met its wait-time service standard; it does **not** include actual wait times.
"""


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    hourly, stats = clean_hourly(read_quarterly_files())
    monthly = clean_monthly()

    hourly.to_csv(OUT_DIR / "windsor_hourly.csv.gz", index=False, date_format="%Y-%m-%dT%H:%M:%S%z")
    monthly.to_csv(OUT_DIR / "windsor_monthly.csv", index=False, date_format="%Y-%m")
    (OUT_DIR / "quality_report.md").write_text(quality_report(stats, monthly), encoding="utf-8")
    print(f"Wrote {len(hourly):,} hourly rows and {len(monthly)} monthly rows to {OUT_DIR}")


if __name__ == "__main__":
    main()
